"""Generate docs/TOOLS.md and the MCP schema snapshot (tests/contract/tool_schemas.json).

    python -m scripts.tool_docs            # write both
    python -m scripts.tool_docs --check    # used by the contract test: exit 1 if signatures drifted
"""
from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path

from agent.mcp_client import ToolBox

ROOT = Path(__file__).resolve().parents[1]
SNAP = ROOT / "tests" / "contract" / "tool_schemas.json"
AUTH = {"portfolio": "bearer JWT (HTTP) / local identity (stdio)", "marketplace": "bearer JWT; marketplace credentials server-side (GigSim token or the user's Upwork OAuth)",
        "workspace": "bearer JWT"}


async def collect() -> list[dict]:
    return await ToolBox("docs", "ai_engineer").list_tools()


def snapshot(tools: list[dict]) -> dict:
    return {f"{t['server']}.{t['name']}": {"input": t["inputSchema"], "output": t["outputSchema"], "annotations": t["annotations"]} for t in tools}


def main() -> None:
    tools = asyncio.run(collect())
    snap = snapshot(tools)
    if "--check" in sys.argv:
        old = json.loads(SNAP.read_text())
        drift = sorted(k for k in set(old) | set(snap) if old.get(k) != snap.get(k))
        print("tool signature drift:", drift or "none"); sys.exit(1 if drift else 0)
    SNAP.write_text(json.dumps(snap, indent=1, sort_keys=True))
    rows = ["| Tool | Server | Read/write | Annotations | Auth | Description |", "|---|---|---|---|---|---|"]
    for t in tools:
        a = t["annotations"]
        rw = "read" if a.get("readOnlyHint") else "write"
        ann = ", ".join(f"{k.replace('Hint', '')}={v}" for k, v in a.items())
        rows.append(f"| `{t['name']}` | {t['server']} | {rw} | {ann} | {AUTH[t['server']]} | {t['description'].split('. ')[0]}. |")
    (ROOT / "docs" / "TOOLS.md").write_text("# MCP tools\n\nGenerated by `python -m scripts.tool_docs` from the live servers; do not edit by hand.\n"
                                            "Writes all require an `idempotency_key` and support `dry_run`. Agent allowlists are in `agent/config.yaml` (`tools.allow`).\n\n"
                                            + "\n".join(rows) + "\n\nResources: `portfolio://case/{id}`, `portfolio://proposal/{id}`, `portfolio://index`.\n"
                                            "Prompts: `answer_screening_question`, `draft_grounded_proposal`, `do_i_have_experience`.\n")
    print(f"wrote docs/TOOLS.md and {SNAP.relative_to(ROOT)} ({len(tools)} tools)")


if __name__ == "__main__":
    main()
